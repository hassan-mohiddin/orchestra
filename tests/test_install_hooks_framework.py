def _make_hook(repo: Path, name: str, content: str) -> Path:
    hooks_dir = repo / ".git" / "hooks"
    hooks_dir.mkdir(parents=True, exist_ok=True)
    p = hooks_dir / name
    p.write_text(content)
    p.chmod(0o755)
    return p


