def test_t5a_apply_preserves_other_repos(tmp_repo: Path, monkeypatch) -> None:
    """Apply: orchestra entry appended; user's other repos preserved."""
    cfg_path = tmp_repo / PRECOMMIT_CONFIG
    cfg_path.write_text(CONFIG_NONE)
    monkeypatch.setattr(
        "cli.install_hooks.subprocess.run",
        lambda *a, **kw: subprocess.CompletedProcess(a, 0, "", ""),
    )
    monkeypatch.setattr("cli.install_hooks.verify_hooks_active", lambda r: 0)
    rc = install_via_framework_apply(tmp_repo)
    assert rc == 0
    import yaml
    after = yaml.safe_load(cfg_path.read_text())
    repos = after["repos"]
    # Original GitHub repo preserved
    assert any(r.get("repo", "").startswith("https://github.com/") for r in repos)
    # Orchestra local entry appended
    assert any(r.get("repo") == "local" for r in repos)


def test_t5b_apply_runs_pre_commit_install_both_types(tmp_repo: Path, monkeypatch) -> None:
    cfg_path = tmp_repo / PRECOMMIT_CONFIG
    cfg_path.write_text(CONFIG_NONE)
    calls: list[list[str]] = []

    def fake_run(cmd, **kw):
        calls.append(cmd)
        return subprocess.CompletedProcess(cmd, 0, "", "")

    monkeypatch.setattr("cli.install_hooks.subprocess.run", fake_run)
    monkeypatch.setattr("cli.install_hooks.verify_hooks_active", lambda r: 0)
    install_via_framework_apply(tmp_repo)
    assert any("pre-commit" in c and "install" in c
               and "--hook-type" in c and "pre-commit" in c and "commit-msg" in c
               for c in calls)


